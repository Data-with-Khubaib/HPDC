export function searchCertificates({ query, status, type, issuedFrom, issuedTo, expiryFrom, expiryTo } = {}) {
  let filtered = [...certificates];

  if (query) {
    const q = query.toLowerCase();
    filtered = filtered.filter(
      (cert) =>
        cert.applicationNo.toLowerCase().includes(q) ||
        cert.certificateId.toLowerCase().includes(q)
    );
  }

  if (status && status !== 'all') {
    filtered = filtered.filter((cert) => cert.status === status);
  }

  if (type && type !== 'all') {
    filtered = filtered.filter((cert) => cert.certificateType === type);
  }

  if (issuedFrom) {
    filtered = filtered.filter((cert) => cert.issuedDate >= issuedFrom);
  }
  if (issuedTo) {
    filtered = filtered.filter((cert) => cert.issuedDate <= issuedTo);
  }
  if (expiryFrom) {
    filtered = filtered.filter((cert) => cert.expiryDate >= expiryFrom);
  }
  if (expiryTo) {
    filtered = filtered.filter((cert) => cert.expiryDate <= expiryTo);
  }

  return filtered;
}

export function paginateCertificates(certs, page = 1, perPage = 20) {
  const total = certs.length;
  const totalPages = Math.ceil(total / perPage);
  const start = (page - 1) * perPage;
  const end = start + perPage;
  return {
    data: certs.slice(start, end),
    total,
    totalPages,
    currentPage: page,
    perPage,
    start: start + 1,
    end: Math.min(end, total),
  };
}
