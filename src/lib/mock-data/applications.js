export function getApplicationById(id) {
  return applications.find((app) => app.id === id);
}

export function getRecentApplications(count = 5) {
  return [...applications]
    .sort((a, b) => new Date(b.submittedDate) - new Date(a.submittedDate))
    .slice(0, count);
}

export function searchApplications(query, statusFilter = 'all') {
  let filtered = applications;
  
  if (statusFilter && statusFilter !== 'all') {
    filtered = filtered.filter((app) => app.status === statusFilter);
  }
  
  if (query) {
    const q = query.toLowerCase();
    filtered = filtered.filter(
      (app) =>
        app.applicationNo.toLowerCase().includes(q) ||
        app.companyName.toLowerCase().includes(q)
    );
  }
  
  return filtered.sort((a, b) => new Date(b.submittedDate) - new Date(a.submittedDate));
}
